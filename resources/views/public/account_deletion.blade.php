    <h1>Request account deletion — Tizzy Cloud</h1>
    <p>
        This page explains how partners can <strong>request</strong> deletion of their Tizzy Cloud
        partner account and associated data. Accounts are <strong>not deleted automatically</strong>
        from the app. Partners and Super Admins cannot hard-delete an account from this flow.
    </p>

    <h2>How to request deletion</h2>
    <ol>
        <li>Open the <strong>Tizzy Cloud</strong> partner app and sign in.</li>
        {{-- Go to Profile → Support & Help → Help Center → Request Account Deletion. --}}
        <li><strong> Go to Profile → Support & Help → Help Center → Request Account Deletion</strong>
            <br>(or contact support with your registered mobile/email).</b></li>
        <li>The app submits a deletion request via our API. You will receive confirmation that the
            request is <em>pending</em>.</li>   
        <li>Our team reviews the request. Processing typically completes within <strong>30 days</strong>
            after verification.</li>
    </ol>

   

    <h2>What happens after you request</h2>
    <ul>
        <li>Your account stays active until the request is processed.</li>
        <li>You cannot delete the account yourself from the app.</li>
        <li>Super Admin does not hard-delete the account from this request screen; status is tracked as a request only.</li>
    </ul>

    <h2>Data deleted vs retained</h2>
    <p><strong>Typically deleted or anonymized after approval:</strong> profile details (name, email, mobile),
        login sessions/tokens, notification preferences, and support chat content tied to the partner profile
        where legally allowed.</p>
    <p><strong>May be retained (legal / tax / billing):</strong> invoices, payment records, GST/tax documents,
        and order history required under Indian tax and regulatory retention rules. Retention may continue for
        up to <strong>8 years</strong> (or longer if required by law).</p>

    <h2>Contact</h2>
    <p>
        For deletion requests or questions, contact support using the email shown on your Play Store listing
        / company website, and include your registered partner mobile or email.
    </p>
